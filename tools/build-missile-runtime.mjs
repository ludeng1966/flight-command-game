import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
const root=new URL('../',import.meta.url),catalog=JSON.parse(fs.readFileSync(new URL('data/flight-research/catalog.json',root)));
const records=catalog.missiles.map(entry=>{
  const r=JSON.parse(fs.readFileSync(new URL('data/flight-research/'+entry.file,root))),g=r.rawRocket.guidance;
  const {id,family,familyName,kind,massKg,finalMassKg,lengthM,diameterM,lifetimeSec,motorStages,aerodynamics,flightControl,launch,proximityFuse,simulationLimits,seeker}=r;
  return {id,family,familyName,kind,massKg,finalMassKg,lengthM,diameterM,lifetimeSec,motorStages,aerodynamics,flightControl,launch,proximityFuse,simulationLimits,seeker,
    guidance:{inertialNavigation:!!g.inertialNavigation,datalink:!!g.inertialGuidance?.datalink,lockDistanceM:g.lockDistance??null,
      radar:g.radarSeeker??null,optical:g.opticalSeeker??null},sourceSha256:r.provenance.sha256};
});
fs.writeFileSync(new URL('data/missile-runtime.js',root),'// Generated by tools/build-missile-runtime.mjs; do not edit by hand.\nexport const MISSILE_DATA='+JSON.stringify(records)+';\n');
console.log('Built '+records.length+' missile configurations at '+fileURLToPath(new URL('data/missile-runtime.js',root)));
